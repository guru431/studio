import { tr } from './i18n.js';
/* Реестр разделов — один источник имён, значков и порядка для рельса и нижней панели (app.js,
 * mobile-navigation.js), заголовков вкладки браузера, «Поиска», «В работе», блокировки, настроек и формы
 * подключения. Порядок — группами: Чат · Фото, Видео · Озвучка, Расшифровка · Сканы, Перевод · Агенты
 * (`group` — номер группы: на рельсе между группами тонкий разделитель). id — адрес (#/<id>) и раздел API,
 * не меняется при смене имени («Озвучка» — id `speech`). Имена совпадают с sections.NAMES сервера —
 * сверяет tests/test_sections_meta.py; словарь — docs/glossary.md. */

export const SECTIONS = [
  { id: 'chat', name: tr("Чат"), group: 1, hint: tr("Чтобы писать в чат, выберите модель в настройках раздела «Чат»") },
  { id: 'photo', name: tr("Фото"), group: 2, hint: tr("Чтобы генерировать фото, выберите модель в настройках раздела «Фото»") },
  { id: 'video', name: tr("Видео"), group: 2, hint: tr("Чтобы делать видео, выберите модель в настройках раздела «Видео»") },
  { id: 'speech', name: tr("Озвучка"), group: 3, hint: tr("Чтобы озвучивать текст, выберите модель в настройках раздела «Озвучка»") },
  { id: 'transcribe', name: tr("Расшифровка"), group: 3,
    hint: tr("Чтобы расшифровывать записи, выберите модель в настройках раздела «Расшифровка»") },
  { id: 'ocr', name: tr("Сканы"), group: 4, hint: tr("Чтобы распознавать сканы, выберите модель в настройках раздела «Сканы»") },
  { id: 'translate', name: tr("Перевод"), group: 4, hint: tr("Чтобы переводить, выберите модель в настройках раздела «Перевод»") },
  { id: 'code', name: tr("Агенты"), group: 5 },
];

/** Имена всех экранов оболочки: восемь разделов и служебные (заголовок вкладки браузера, голосовой ввод в настройках). */
export const NAMES = {
  ...Object.fromEntries(SECTIONS.map((s) => [s.id, s.name])),
  dictation: tr("Голосовой ввод"),
  search: tr("Поиск"),
  settings: tr("Настройки"),
  admin: tr("Администрирование"),
};

/** Имя раздела по id; неизвестный id — сам id. */
export function sectionName(id) {
  return NAMES[id] || id;
}

/** [id, имя] разделов в порядке рельса; `only` — оставить только эти id. */
export function sectionPairs(only = null) {
  return SECTIONS.filter((s) => !only || only.includes(s.id)).map((s) => [s.id, s.name]);
}
