/* Реестр разделов — один источник имён, значков и порядка для рельса и нижней панели (app.js,
 * mobile-navigation.js), заголовков вкладки браузера, «Поиска», «В работе», блокировки, настроек и формы
 * подключения. Порядок — группами: Чат · Фото, Видео · Озвучка, Расшифровка · Сканы, Перевод · Агенты
 * (`group` — номер группы: на рельсе между группами тонкий разделитель). id — адрес (#/<id>) и раздел API,
 * не меняется при смене имени («Озвучка» — id `speech`). Имена совпадают с sections.NAMES сервера —
 * сверяет tests/test_sections_meta.py; словарь — docs/glossary.md. */

export const SECTIONS = [
  { id: 'chat', name: 'Чат', group: 1, hint: 'Чтобы писать в чат, выберите модель в настройках раздела «Чат»' },
  { id: 'photo', name: 'Фото', group: 2, hint: 'Чтобы генерировать фото, выберите модель в настройках раздела «Фото»' },
  { id: 'video', name: 'Видео', group: 2, hint: 'Чтобы делать видео, выберите модель в настройках раздела «Видео»' },
  { id: 'speech', name: 'Озвучка', group: 3, hint: 'Чтобы озвучивать текст, выберите модель в настройках раздела «Озвучка»' },
  { id: 'transcribe', name: 'Расшифровка', group: 3,
    hint: 'Чтобы расшифровывать записи, выберите модель в настройках раздела «Расшифровка»' },
  { id: 'ocr', name: 'Сканы', group: 4, hint: 'Чтобы распознавать сканы, выберите модель в настройках раздела «Сканы»' },
  { id: 'translate', name: 'Перевод', group: 4, hint: 'Чтобы переводить, выберите модель в настройках раздела «Перевод»' },
  { id: 'code', name: 'Агенты', group: 5 },
];

/** Имена всех экранов оболочки: восемь разделов и служебные (заголовок вкладки браузера, голосовой ввод в настройках). */
export const NAMES = {
  ...Object.fromEntries(SECTIONS.map((s) => [s.id, s.name])),
  dictation: 'Голосовой ввод',
  search: 'Поиск',
  settings: 'Настройки',
  admin: 'Администрирование',
};

/** Имя раздела по id; неизвестный id — сам id. */
export function sectionName(id) {
  return NAMES[id] || id;
}

/** [id, имя] разделов в порядке рельса; `only` — оставить только эти id. */
export function sectionPairs(only = null) {
  return SECTIONS.filter((s) => !only || only.includes(s.id)).map((s) => [s.id, s.name]);
}
